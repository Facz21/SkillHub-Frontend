import { request } from "./apiClient";
import { Enrollment } from "@/types/enrollment";

/**
 * Service handling participant workshop enrollments, cancellations,
 * and PDF attendance certificate generation (/api/v1/enrollments/*).
 */
export const enrollmentService = {
  /**
   * Enrolls the authenticated participant into the specified workshop.
   */
  async enroll(workshopId: number): Promise<Enrollment> {
    return request<Enrollment>("/enrollments", {
      method: "POST",
      body: JSON.stringify({ workshopId }),
    });
  },

  /**
   * Retrieves all active and cancelled enrollments belonging to the authenticated participant.
   */
  async getMyEnrollments(): Promise<Enrollment[]> {
    return request<Enrollment[]>("/enrollments/mine");
  },

  /**
   * Cancels an active enrollment and immediately releases the seat.
   */
  async cancelEnrollment(enrollmentId: number): Promise<Enrollment> {
    return request<Enrollment>(`/enrollments/${enrollmentId}/cancel`, {
      method: "PATCH",
    });
  },

  /**
   * Downloads the official PDF attendance certificate generated by QuestPDF on the backend.
   */
  async downloadCertificate(enrollmentId: number): Promise<Blob> {
    const blob = await request<Blob>(`/enrollments/${enrollmentId}/certificate`);
    
    // Auto-download trigger if running in browser environment
    if (typeof window !== "undefined" && blob) {
      const url = window.URL.createObjectURL(blob);
      const a = document.createElement("a");
      a.href = url;
      a.download = `Certificado_SkillHub_${enrollmentId}.pdf`;
      document.body.appendChild(a);
      a.click();
      window.URL.revokeObjectURL(url);
      a.remove();
    }

    return blob;
  },
};
