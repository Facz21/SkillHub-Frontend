import { request } from "./apiClient";
import {
  AuthResponse,
  AuthTokenDispatchResponse,
  UserProfileResponse,
} from "@/types/auth";

/**
 * Service encapsulating all Identity and Authentication API calls (/api/v1/auth/*),
 * including login with RememberMe, registration, password reset, and email confirmation.
 */
export const authService = {
  /**
   * Authenticates a user and returns a JWT token (7-day expiration if rememberMe is true, 2-hour otherwise).
   */
  async login(
    email: string,
    password: string,
    rememberMe: boolean = true
  ): Promise<AuthResponse> {
    return request<AuthResponse>("/auth/login", {
      method: "POST",
      body: JSON.stringify({ email, password, rememberMe }),
    });
  },

  /**
   * Registers a new participant account and triggers an email confirmation token via SMTP.
   */
  async register(
    fullName: string,
    email: string,
    password: string
  ): Promise<AuthResponse> {
    return request<AuthResponse>("/auth/register", {
      method: "POST",
      body: JSON.stringify({ fullName, email, password }),
    });
  },

  /**
   * Requests a password reset token to be sent via SMTP to the user's email address.
   */
  async forgotPassword(email: string): Promise<AuthTokenDispatchResponse> {
    return request<AuthTokenDispatchResponse>("/auth/forgot-password", {
      method: "POST",
      body: JSON.stringify({ email }),
    });
  },

  /**
   * Resets a user's password using the cryptographic token generated by ASP.NET Core Identity.
   */
  async resetPassword(
    email: string,
    token: string,
    newPassword: string
  ): Promise<{ message: string }> {
    return request<{ message: string }>("/auth/reset-password", {
      method: "POST",
      body: JSON.stringify({ email, token, newPassword }),
    });
  },

  /**
   * Resends the email verification token to an unverified account.
   */
  async resendConfirmation(email: string): Promise<AuthTokenDispatchResponse> {
    return request<AuthTokenDispatchResponse>("/auth/resend-confirmation", {
      method: "POST",
      body: JSON.stringify({ email }),
    });
  },

  /**
   * Confirms a user's email address using the verification token sent upon registration.
   */
  async confirmEmail(
    email: string,
    token: string
  ): Promise<{ message: string }> {
    return request<{ message: string }>("/auth/confirm-email", {
      method: "POST",
      body: JSON.stringify({ email, token }),
    });
  },

  /**
   * Retrieves the authenticated user's profile and email verification status.
   */
  async getProfile(): Promise<UserProfileResponse> {
    return request<UserProfileResponse>("/auth/profile");
  },

  /**
   * Updates the authenticated user's full name and optional specialty.
   */
  async updateProfile(
    fullName: string,
    specialty?: string
  ): Promise<UserProfileResponse> {
    return request<UserProfileResponse>("/auth/profile", {
      method: "PUT",
      body: JSON.stringify({ fullName, specialty }),
    });
  },

  /**
   * Changes the authenticated user's password after verifying the current password.
   */
  async changePassword(
    currentPassword: string,
    newPassword: string
  ): Promise<{ message: string }> {
    return request<{ message: string }>("/auth/change-password", {
      method: "PUT",
      body: JSON.stringify({ currentPassword, newPassword }),
    });
  },
};
